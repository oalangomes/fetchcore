import { test, expect } from '@playwright/test'

test('real Solr search → provenance → authorized source read (FetchCore)', async ({ page }) => {
  await page.goto('/')
  await expect(page.getByText('API conectada')).toBeVisible()
  await expect(page.getByText('solr', { exact: true }).first()).toBeVisible()
  await page.getByLabel('Canonical query').fill('eligibility_validator')
  await page.getByTestId('run-search').click()

  await expect(page.getByText('Trecho recuperado')).toBeVisible()
  await expect(page.getByLabel('Repositório autorizado')).toHaveValue('demo/catalog')
  await expect(page.getByLabel('Coleção / índice configurado')).toHaveValue('default')
  await expect(page.getByText('Destino: default')).toBeVisible()
  await expect(page.getByText(/eligibility.py/).first()).toBeVisible()
  await expect(page.getByText('QueryMatchEvidence')).toBeVisible()
  await expect(page.getByText('Provenance e identidade')).toBeVisible()

  await page.getByRole('tab', { name: 'Código-fonte' }).click()
  await expect(page.locator('pre.code-output').filter({ hasText: 'def eligibility_validator' })).toBeVisible()
  await page.getByRole('button', { name: 'Telemetry' }).click()
  await expect(page.getByText('Estágios de aquisição')).toBeVisible()
})

test('real Solr visual OR query preserves declared branches and provenance', async ({ page }) => {
  await page.goto('/')
  await expect(page.getByText('API conectada')).toBeVisible()
  await page.getByRole('button', { name: '+ OR · qualquer alternativa' }).click()
  await page.getByLabel('Termo branch 0').fill('eligibility_validator')
  await page.getByRole('button', { name: '+ Anchor obrigatório' }).click()
  await page.getByLabel('Anchor branch 1').fill('eligibility.py')
  await page.getByLabel('Origem branch 1').fill('caller')
  await page.getByRole('button', { name: 'Inspecionar payload final' }).click()
  await expect(page.getByLabel('JSON final da busca')).toContainText('"any_of"')
  await expect(page.getByLabel('JSON final da busca')).toContainText('"caller"')
  await page.getByRole('button', { name: 'JSON completo' }).click()
  await expect(page.getByLabel('SearchIntent JSON')).toBeVisible()
  await page.getByRole('button', { name: 'Formulário' }).click()
  await expect(page.getByLabel('Anchor branch 1')).toHaveValue('eligibility.py')
  await page.getByTestId('run-search').click()
  await expect(page.getByText('Trecho recuperado')).toBeVisible()
  await expect(page.getByText('Provenance e identidade')).toBeVisible()
})
