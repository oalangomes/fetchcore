test('real Solr history capture, restore, and strict replay rejection for unbound revision', async ({ page }) => {
  await page.goto('/')
  await expect(page.getByText('API conectada')).toBeVisible()
  await page.getByLabel('Canonical query').fill('eligibility_validator')
  await page.getByTestId('run-search').click()
  await expect(page.getByText('Trecho recuperado')).toBeVisible()
  await expect(page.getByLabel('Histórico de execuções').getByText('1/20')).toBeVisible()
  await page.getByLabel('Canonical query').fill('altered draft')
  await page.getByRole('button', { name: 'Restaurar query' }).click()
  await expect(page.getByLabel('Canonical query')).toHaveValue('eligibility_validator')
  await page.getByRole('button', { name: 'Replay verificado' }).click()
  await expect(page.getByLabel('Histórico de execuções').getByRole('status'))
    .toContainText('não há garantia de replay equivalente')
  await expect(page.getByLabel('Histórico de execuções').getByText('1/20')).toBeVisible()
  await page.getByRole('button', { name: 'Limpar', exact: true }).click()
  await page.getByRole('button', { name: 'Confirmar limpeza' }).click()
  await expect(page.getByLabel('Histórico de execuções').getByText('0/20')).toBeVisible()
})

test('real Solr comparison A/B shows observed candidates and incompatible snapshot controls', async ({ page }) => {
  await page.goto('/')
  await expect(page.getByText('API conectada')).toBeVisible()
  await page.getByLabel('Canonical query').fill('eligibility_validator')
  await page.getByTestId('run-search').click()
  await expect(page.getByLabel('Histórico de execuções').getByText('1/20')).toBeVisible()
  await page.getByTestId('run-search').click()
  await expect(page.getByLabel('Histórico de execuções').getByText('2/20')).toBeVisible()
  const comparison = page.getByLabel('Retrieval Comparison Lab')
  await expect(comparison.getByText('A × B', { exact: false })).toBeVisible()
  await expect(comparison.getByText('Corpus/repository revision não comprovadamente idênticos')).toBeVisible()
  await expect(comparison.getByLabel('Diferenças dos candidatos')).toBeVisible()
  await expect(comparison.getByText('Tempo total')).toBeVisible()
  await comparison.getByRole('button', { name: 'Somente B' }).click()
  await expect(comparison.getByText('Nenhuma identidade nesta seleção.')).toBeVisible()
})

